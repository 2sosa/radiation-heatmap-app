def generate_tube_mesh(
    centerline: List[Vector3],
    radius: float,
    segments: int,
    colors: List[Tuple[int, int, int]],
) -> Tuple[List[Tuple[float, float, float, int, int, int]], List[Tuple[int, int, int]]]:
    """
    Returns (vertices, faces)
     - vertices: list of (x, y, z, r, g, b)
     - faces: list of (i0, i1, i2) triangle indices
    The color at each ring is constant across its vertices and taken from colors[i].
    """
    if len(centerline) == 0:
        return ([], [])
    if segments < 3:
        segments = 3

    vertices: List[Tuple[float, float, float, int, int, int]] = []
    faces: List[Tuple[int, int, int]] = []

    up_ref: Vector3 = (0.0, 0.0, 1.0)

    # Precompute ring frames and vertices
    ring_vertex_indices: List[List[int]] = []
    for i, p in enumerate(centerline):
        # Tangent
        if i == 0:
            t_vec = vector_sub(centerline[1], centerline[0]) if len(centerline) > 1 else (1.0, 0.0, 0.0)
        elif i == len(centerline) - 1:
            t_vec = vector_sub(centerline[i], centerline[i - 1])
        else:
            t_vec = vector_sub(centerline[i + 1], centerline[i - 1])
        t_hat = vector_normalize(t_vec)
        if vector_length(t_hat) < 1e-9:
            t_hat = (1.0, 0.0, 0.0)

        # Choose normal not parallel to tangent
        ref = up_ref
        if abs(vector_dot(t_hat, ref)) > 0.95:
            ref = (0.0, 1.0, 0.0)
        n_vec = vector_cross(t_hat, ref)
        n_hat = vector_normalize(n_vec)
        if vector_length(n_hat) < 1e-9:
            # Fallback
            ref = (1.0, 0.0, 0.0)
            n_hat = vector_normalize(vector_cross(t_hat, ref))
        b_hat = vector_cross(t_hat, n_hat)
        b_hat = vector_normalize(b_hat)

        ring_indices: List[int] = []
        col = colors[i]
        for s in range(segments):
            theta = 2.0 * math.pi * (float(s) / float(segments))
            offset = vector_add(vector_scale(n_hat, math.cos(theta) * radius), vector_scale(b_hat, math.sin(theta) * radius))
            v = vector_add(p, offset)
            idx = len(vertices)
            vertices.append((v[0], v[1], v[2], col[0], col[1], col[2]))
            ring_indices.append(idx)
        ring_vertex_indices.append(ring_indices)

    # Create faces between consecutive rings
    for i in range(len(ring_vertex_indices) - 1):
        ring_a = ring_vertex_indices[i]
        ring_b = ring_vertex_indices[i + 1]
        for s in range(segments):
            a0 = ring_a[s]
            a1 = ring_a[(s + 1) % segments]
            b0 = ring_b[s]
            b1 = ring_b[(s + 1) % segments]
            # Split quad into two triangles: (a0, a1, b1) and (a0, b1, b0)
            faces.append((a0, a1, b1))
            faces.append((a0, b1, b0))

    return (vertices, faces)


# ------------------------------
# PLY writer
# ------------------------------


def write_ply_ascii(
    out_path: str,
    vertices: List[Tuple[float, float, float, int, int, int]],
    faces: List[Tuple[int, int, int]],
) -> None:
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("ply\n")
        f.write("format ascii 1.0\n")
        f.write(f"element vertex {len(vertices)}\n")
        f.write("property float x\n")
        f.write("property float y\n")
        f.write("property float z\n")
        f.write("property uchar red\n")
        f.write("property uchar green\n")
        f.write("property uchar blue\n")
        f.write(f"element face {len(faces)}\n")
        f.write("property list uchar int vertex_indices\n")
        f.write("end_header\n")

        for (x, y, z, r, g, b) in vertices:
            f.write(f"{x:.6f} {y:.6f} {z:.6f} {int(r)} {int(g)} {int(b)}\n")
        for (i0, i1, i2) in faces:
            f.write(f"3 {i0} {i1} {i2}\n")


