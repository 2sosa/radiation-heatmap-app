#!/usr/bin/env python3
"""
Heatline Generator

Purpose:
  - Parse Polycam JSON to extract SLAM trajectory (timestamps + positions)
  - Parse AccuRad PRD CSV to extract dose rate timeline (\u00b5Sv/h)
  - Align timelines with optional manual offset and linear interpolation
  - Generate a colored tube mesh (diameter = 0.1 m by default) along the trajectory
  - Export as ASCII PLY with per-vertex RGB colors (blue\u2192red across dose range)

Notes:
  - Implemented without heavy dependencies to work in Pythonista and standard Python.
  - Polycam JSON schemas vary; this script tries several common patterns and falls back
    to heuristic extraction of timestamps and positions.
  - AccuRad CSV formats vary; we detect likely time and dose columns. Provide
    --time-column and --dose-column to override if needed, and --date-column if
    date and time are split.

CLI Example:
  python heatline_generator.py \
    --polycam-json polycam_export.json \
    --accurad-csv accurad_log.csv \
    --out-ply heatline.ply \
    --radius 0.05 \
    --dose-min 0 --dose-max 10 \
    --time-offset 0

Author: Generated by AI assistant
"""

import argparse
import csv
import json
import math
import os
import sys
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple


# ------------------------------
# Utility: simple vector math
# ------------------------------

Vector3 = Tuple[float, float, float]


def vector_add(a: Vector3, b: Vector3) -> Vector3:
    return (a[0] + b[0], a[1] + b[1], a[2] + b[2])


def vector_sub(a: Vector3, b: Vector3) -> Vector3:
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def vector_scale(a: Vector3, s: float) -> Vector3:
    return (a[0] * s, a[1] * s, a[2] * s)


def vector_dot(a: Vector3, b: Vector3) -> float:
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def vector_cross(a: Vector3, b: Vector3) -> Vector3:
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def vector_length(a: Vector3) -> float:
    return math.sqrt(vector_dot(a, a))


def vector_normalize(a: Vector3) -> Vector3:
    length = vector_length(a)
    if length <= 1e-12:
        return (0.0, 0.0, 0.0)
    inv = 1.0 / length
    return (a[0] * inv, a[1] * inv, a[2] * inv)


def is_finite_vec(v: Vector3) -> bool:
    return math.isfinite(v[0]) and math.isfinite(v[1]) and math.isfinite(v[2])


# ------------------------------
# Color mapping (\u00b5Sv/h \u2192 RGB)
# ------------------------------


def clamp(v: float, vmin: float, vmax: float) -> float:
    if v < vmin:
        return vmin
    if v > vmax:
        return vmax
    return v


def lerp(a: float, b: float, t: float) -> float:
    return a + (b - a) * t


def color_blue_to_red(value: float, vmin: float, vmax: float) -> Tuple[int, int, int]:
    """
    Map value in [vmin, vmax] to an RGB color from blue (low) to red (high).
    Simple two-point gradient: blue -> red. Returns 0-255 ints.
    """
    if not math.isfinite(value):
        value = vmin
    if vmax <= vmin:
        t = 0.0
    else:
        t = (clamp(value, vmin, vmax) - vmin) / (vmax - vmin)
    # Blue to red linear blend
    r = int(round(lerp(0, 255, t)))
    g = 0
    b = int(round(lerp(255, 0, t)))
    return (r, g, b)


