def build_heatline(
    polycam_json_path: str,
    accurad_csv_path: str,
    out_ply_path: str,
    radius: float,
    segments: int,
    dose_min: float,
    dose_max: float,
    time_offset: float,
    time_scale: float,
    time_clip: Optional[Tuple[float, float]] = None,
    time_column: Optional[str] = None,
    dose_column: Optional[str] = None,
    date_column: Optional[str] = None,
) -> None:
    # Parse inputs
    traj = parse_polycam_json_positions(polycam_json_path)
    dose = parse_accurad_csv(
        accurad_csv_path,
        time_column=time_column,
        dose_column=dose_column,
        date_column=date_column,
    )

    # Apply time scaling/clipping to trajectory if requested
    traj_times = [t * time_scale for (t, _) in traj]
    traj_points = [p for (_, p) in traj]

    if time_clip is not None:
        tmin, tmax = time_clip
        clipped_times: List[float] = []
        clipped_points: List[Vector3] = []
        for t, p in zip(traj_times, traj_points):
            if tmin <= t <= tmax:
                clipped_times.append(t)
                clipped_points.append(p)
        traj_times = clipped_times
        traj_points = clipped_points

    if len(traj_points) < 2:
        raise ValueError("Trajectory has fewer than 2 points after filtering.")

    # Interpolate dose at trajectory timestamps
    doses = interpolate_dose_at_times(dose, traj_times, time_offset=time_offset)

    # Map to colors for each ring
    colors = [color_blue_to_red(d, dose_min, dose_max) for d in doses]

    vertices, faces = generate_tube_mesh(traj_points, radius, segments, colors)

    write_ply_ascii(out_ply_path, vertices, faces)


def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Generate a colored tube 'heatline' along Polycam SLAM trajectory using AccuRad dose data."
        )
    )
    parser.add_argument("--polycam-json", required=True, help="Path to Polycam JSON export containing trajectory/poses")
    parser.add_argument("--accurad-csv", required=True, help="Path to AccuRad CSV with timestamps and dose rate (\u00b5Sv/h)")
    parser.add_argument("--out-ply", required=True, help="Output PLY path for heatline tube")

    parser.add_argument("--radius", type=float, default=0.05, help="Tube radius in meters (default 0.05 m for 10 cm diameter)")
    parser.add_argument("--segments", type=int, default=16, help="Number of radial segments for tube (default 16)")

    parser.add_argument("--dose-min", type=float, default=0.0, help="Lower bound of dose range for color mapping (\u00b5Sv/h)")
    parser.add_argument("--dose-max", type=float, default=10.0, help="Upper bound of dose range for color mapping (\u00b5Sv/h)")

    parser.add_argument("--time-offset", type=float, default=0.0, help="Add offset (seconds) to AccuRad dose timeline to align with SLAM")
    parser.add_argument(
        "--time-scale",
        type=float,
        default=1.0,
        help="Multiply Polycam trajectory timestamps by this factor (for unit mismatches)",
    )
    parser.add_argument(
        "--time-clip",
        type=float,
        nargs=2,
        metavar=("TMIN", "TMAX"),
        help="Clip trajectory times to [TMIN, TMAX] after scaling",
    )

    parser.add_argument("--time-column", type=str, default=None, help="CSV header name of time column (override auto-detect)")
    parser.add_argument("--date-column", type=str, default=None, help="CSV header name of date column when date/time split")
    parser.add_argument("--dose-column", type=str, default=None, help="CSV header name of dose column (override auto-detect)")

    return parser.parse_args(argv)


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)
    try:
        build_heatline(
            polycam_json_path=args.polycam_json,
            accurad_csv_path=args.accurad_csv,
            out_ply_path=args.out_ply,
            radius=args.radius,
            segments=args.segments,
            dose_min=args.dose_min,
            dose_max=args.dose_max,
            time_offset=args.time_offset,
            time_scale=args.time_scale,
            time_clip=tuple(args.time_clip) if args.time_clip is not None else None,
            time_column=args.time_column,
            dose_column=args.dose_column,
            date_column=args.date_column,
        )
    except Exception as e:
        sys.stderr.write(f"Error: {e}\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

