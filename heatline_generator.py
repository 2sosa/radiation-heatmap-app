def _extract_position_from_transform(transform: Sequence[float]) -> Optional[Vector3]:
    """
    Accepts a 16-length (row-major) transform or 12-length 3x4 matrix.
    Returns translation component.
    """
    try:
        if transform is None:
            return None
        flist = list(float(x) for x in transform)
        if len(flist) == 16:
            # 4x4 row-major
            return (flist[3], flist[7], flist[11])
        if len(flist) == 12:
            # 3x4 row-major
            return (flist[3], flist[7], flist[11])
        if len(flist) == 9:
            # 3x3; no translation
            return None
    except Exception:
        return None
    return None


def _to_float(value: Any) -> Optional[float]:
    if value is None:
        return None
    if isinstance(value, (int, float)):
        return float(value)
    if isinstance(value, str):
        try:
            return float(value.strip())
        except Exception:
            return None
    return None


def _try_keys(d: Dict[str, Any], keys: Sequence[str]) -> Any:
    for k in keys:
        if k in d:
            return d[k]
    return None


def parse_polycam_json_positions(json_path: str) -> List[Tuple[float, Vector3]]:
    """
    Returns list of (timestamp_seconds, position_meters) in world coordinates.
    The JSON schema is probed for several common layouts.
    """
    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    frames: List[Dict[str, Any]] = []

    # Common containers
    if isinstance(data, dict):
        for key in [
            "frames",
            "cameraPoses",
            "poses",
            "trajectory",
            "records",
            "scans",
        ]:
            val = data.get(key)
            if isinstance(val, list) and len(val) > 0 and isinstance(val[0], dict):
                frames = val
                break
        # Some exports may directly be a list of frames under top-level
        if not frames and isinstance(data.get("0"), dict):
            # Not typical; ignore
            pass
    if not frames and isinstance(data, list) and data and isinstance(data[0], dict):
        frames = data

    if not frames:
        raise ValueError(
            "Unsupported Polycam JSON structure: could not find frames/poses list."
        )

    results: List[Tuple[float, Vector3]] = []

    for fr in frames:
        # Candidate timestamp fields
        t_val = _try_keys(fr, [
            "timestamp",
            "time",
            "t",
            "time_seconds",
            "timeSec",
            "ts",
        ])
        ts = _to_float(t_val)

        # If time is missing but there is an index, allow monotonic index seconds
        if ts is None:
            idx = _try_keys(fr, ["index", "frame", "i"])
            if isinstance(idx, int):
                ts = float(idx)
            elif isinstance(idx, str) and idx.isdigit():
                ts = float(int(idx))

        # Candidate position fields
        pos: Optional[Vector3] = None
        pos_val = _try_keys(fr, [
            "position",
            "translation",
            "location",
            "xyz",
        ])
        if isinstance(pos_val, (list, tuple)) and len(pos_val) >= 3:
            try:
                pos = (float(pos_val[0]), float(pos_val[1]), float(pos_val[2]))
            except Exception:
                pos = None

        # Transform matrix candidates
        if pos is None:
            for k in [
                "transform",
                "pose",
                "matrix",
                "worldTransform",
                "cameraTransform",
            ]:
                m = fr.get(k)
                if isinstance(m, (list, tuple)):
                    # Flat or nested matrix
                    if len(m) in (9, 12, 16):
                        pos = _extract_position_from_transform(m)
                    elif len(m) == 4 and all(isinstance(row, (list, tuple)) for row in m):
                        flat = []
                        for row in m:
                            flat.extend(row)
                        pos = _extract_position_from_transform(flat)
                if pos is not None:
                    break

        if ts is None or pos is None:
            # Skip unparseable frame
            continue

        if not is_finite_vec(pos):
            continue

        results.append((float(ts), pos))

    # Sort by time to ensure monotonic order
    results.sort(key=lambda x: x[0])

    if not results:
        raise ValueError("No valid (timestamp, position) entries found in Polycam JSON.")

    return results


