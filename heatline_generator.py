def _parse_datetime_string(dt_str: str) -> Optional[float]:
    """
    Try parsing a datetime string into POSIX seconds (naive local time).
    Supports common formats with optional milliseconds.
    Returns None if parsing fails.
    """
    dt_str = dt_str.strip()
    # Numeric epoch seconds
    try:
        return float(dt_str)
    except Exception:
        pass

    fmts = [
        "%Y-%m-%d %H:%M:%S.%f",
        "%Y-%m-%d %H:%M:%S",
        "%Y/%m/%d %H:%M:%S.%f",
        "%Y/%m/%d %H:%M:%S",
        "%m/%d/%Y %H:%M:%S.%f",
        "%m/%d/%Y %H:%M:%S",
        "%d/%m/%Y %H:%M:%S.%f",
        "%d/%m/%Y %H:%M:%S",
        "%Y-%m-%dT%H:%M:%S.%f",
        "%Y-%m-%dT%H:%M:%S",
    ]
    import datetime as _dt

    for fmt in fmts:
        try:
            dt = _dt.datetime.strptime(dt_str, fmt)
            # Interpret as naive local time; convert to POSIX
            epoch = _dt.datetime(1970, 1, 1)
            return (dt - epoch).total_seconds()
        except Exception:
            continue
    return None


def _find_column_idx(headers: List[str], candidates: Sequence[str]) -> Optional[int]:
    lc = [h.strip().lower() for h in headers]
    for i, h in enumerate(lc):
        for c in candidates:
            if c in h:
                return i
    return None


def parse_accurad_csv(
    csv_path: str,
    time_column: Optional[str] = None,
    dose_column: Optional[str] = None,
    date_column: Optional[str] = None,
) -> List[Tuple[float, float]]:
    """
    Returns list of (timestamp_seconds, dose_rate_uSv_per_h).
    Attempts to detect time and dose columns; parameters can override.
    """
    with open(csv_path, "r", encoding="utf-8", newline="") as f:
        sample = f.read(4096)
        f.seek(0)
        try:
            dialect = csv.Sniffer().sniff(sample, delimiters=",;\t|")
        except Exception:
            dialect = csv.excel
        reader = csv.reader(f, dialect)
        try:
            headers = next(reader)
        except StopIteration:
            raise ValueError("Empty CSV file")

        headers_norm = [h.strip() for h in headers]

        # Resolve column indexes
        if time_column is not None and time_column in headers_norm:
            time_idx = headers_norm.index(time_column)
        else:
            time_idx = _find_column_idx(headers_norm, [
                "datetime",
                "timestamp",
                "time",
                "date/time",
            ])

        if date_column is not None and date_column in headers_norm:
            date_idx = headers_norm.index(date_column)
        else:
            # Detect separate date field if present
            date_idx = _find_column_idx(headers_norm, ["date"])

        if dose_column is not None and dose_column in headers_norm:
            dose_idx = headers_norm.index(dose_column)
        else:
            dose_idx = _find_column_idx(headers_norm, [
                "\u00b5sv/h",
                "usv/h",
                "usv",
                "dose rate",
                "dose_rate",
                "rate (usv/h)",
                "u(s)v/h",
                "radiation",
            ])

        if time_idx is None and (date_idx is None):
            raise ValueError(
                "Could not detect time column. Use --time-column (and optionally --date-column)."
            )
        if dose_idx is None:
            raise ValueError("Could not detect dose column. Use --dose-column to specify.")

        points: List[Tuple[float, float]] = []
        for row in reader:
            if not row or len(row) < 1:
                continue
            # Build timestamp string
            ts_str: Optional[str] = None
            if date_idx is not None and time_idx is not None and date_idx < len(row) and time_idx < len(row):
                ts_str = f"{row[date_idx].strip()} {row[time_idx].strip()}"
            elif time_idx is not None and time_idx < len(row):
                ts_str = row[time_idx].strip()
            elif date_idx is not None and date_idx < len(row):
                ts_str = row[date_idx].strip()

            ts_val: Optional[float] = None
            if ts_str is not None and ts_str != "":
                ts_val = _parse_datetime_string(ts_str)

            # Dose rate
            dose_val: Optional[float] = None
            if dose_idx < len(row):
                try:
                    cell = row[dose_idx].strip().replace(",", "")
                    # Remove unit strings
                    for unit_str in ["\u00b5Sv/h", "uSv/h", "usv/h", "usv", "uSv", "\u00b5Sv"]:
                        cell = cell.replace(unit_str, "")
                    dose_val = float(cell)
                except Exception:
                    dose_val = None

            if ts_val is None or dose_val is None:
                continue

            points.append((ts_val, dose_val))

    points.sort(key=lambda x: x[0])
    if not points:
        raise ValueError("No valid (timestamp, dose) rows parsed from CSV.")
    return points


# ------------------------------
# Timeline alignment and interpolation
# ------------------------------


def interpolate_dose_at_times(
    dose_timeline: List[Tuple[float, float]],
    query_times: List[float],
    time_offset: float = 0.0,
) -> List[float]:
    """
    For each query time, linearly interpolate dose_timeline to get dose value.
    time_offset shifts dose timeline by seconds (positive moves dose forward in time).
    """
    # Shift dose timeline
    shifted = [(t + time_offset, d) for (t, d) in dose_timeline]
    shifted.sort(key=lambda x: x[0])

    # Two-pointer interpolation
    doses: List[float] = []
    j = 0
    n = len(shifted)
    for qt in query_times:
        while j + 1 < n and shifted[j + 1][0] < qt:
            j += 1
        if n == 0:
            doses.append(float("nan"))
            continue
        if qt <= shifted[0][0]:
            doses.append(shifted[0][1])
            continue
        if qt >= shifted[-1][0]:
            doses.append(shifted[-1][1])
            continue
        # j is last point with t <= qt
        k = j + 1
        t0, d0 = shifted[j]
        t1, d1 = shifted[k]
        if t1 == t0:
            doses.append(d0)
        else:
            t = (qt - t0) / (t1 - t0)
            doses.append(d0 + (d1 - d0) * t)
    return doses


